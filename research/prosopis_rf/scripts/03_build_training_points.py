"""Step 3: turn the visual decisions into the hand-picked training points used by banni_rf.js.

Reads labelling/visual_labels.csv (one row per candidate: accepted / relabelled / rejected after looking at its image chip),
keeps accepted and relabelled points, and thins them so no two kept points are closer than MIN_SPACING_M (any class).
Nearby points sit on the same patch and would make the held-out accuracy look better than it is.

Writes
  labelling/training_points.csv            the final points (id, class, lon, lat)
  ../gee/manual_points.js                  the four FeatureCollections banni_rf.js expects:
                                           manualPros, manualMix, manualWater, manualBrush
Run from the repository root:  .venv\\Scripts\\python research\\prosopis_rf\\scripts\\03_build_training_points.py
"""
import csv
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BASE = ROOT / "research" / "prosopis_rf"
LAB = BASE / "labelling"
MIN_SPACING_M = 150
CLASSES = [("pros", 1, "manualPros", "Prosopis woodland"), ("mix", 2, "manualMix", "Mixed Prosopis + grass"),
           ("water", 3, "manualWater", "Wetland / water"), ("brush", 4, "manualBrush", "Saline brushland")]
# Zenodo field sites already in banni_rf.js (UTM 42N converted to lon/lat); hand-picked points must not duplicate them
ZENODO = [(69.2648, 23.69517), (69.52009, 23.751), (69.30162, 23.61979), (69.30167, 23.72784), (69.3409, 23.72933),
          (69.45353, 23.61776), (69.37987, 23.58293), (69.37995, 23.61886), (69.41916, 23.58339), (69.45809, 23.58318)]


def dist_m(a, b):
    lat = math.radians((a[1] + b[1]) / 2)
    return math.hypot((a[0] - b[0]) * 111320 * math.cos(lat), (a[1] - b[1]) * 110540)


def main():
    rows = [r for r in csv.DictReader((LAB / "visual_labels.csv").open()) if r["decision"] in ("accepted", "relabelled")]
    kept, dropped = [], 0
    for r in rows:                                    # file order: round 1 first, then round 2
        p = (float(r["lon"]), float(r["lat"]))
        if any(dist_m(p, (float(k["lon"]), float(k["lat"]))) < MIN_SPACING_M for k in kept) or \
           any(dist_m(p, z) < MIN_SPACING_M for z in ZENODO):
            dropped += 1
            continue
        kept.append(r)
    with (LAB / "training_points.csv").open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["point_id", "class_code", "class_name", "lon", "lat", "source_candidate", "decision"])
        for key, code, _, name in CLASSES:
            for i, r in enumerate([k for k in kept if k["label"] == key], 1):
                w.writerow([f"{key}_{i:02d}", code, name, r["lon"], r["lat"], r["cand_id"], r["decision"]])
    lines = ["// Hand-picked training points for banni_rf.js (generated by research/prosopis_rf/scripts/03_build_training_points.py).",
             "// Each point was labelled by eye on Esri World Imagery (~1.1 m) and is at least "
             f"{MIN_SPACING_M} m from every other point and from the Zenodo field sites.",
             "// Paste ABOVE banni_rf.js in the Code Editor: these replace the geometry imports drawn by hand.", ""]
    counts = {}
    for key, code, var, name in CLASSES:
        pts = [k for k in kept if k["label"] == key]
        counts[name] = len(pts)
        body = ",\n  ".join(f"ee.Feature(ee.Geometry.Point([{p['lon']}, {p['lat']}]))" for p in pts)
        lines += [f"// {name}: {len(pts)} points", f"var {var} = ee.FeatureCollection([\n  {body}\n]);", ""]
    (BASE / "gee").mkdir(exist_ok=True)
    (BASE / "gee" / "manual_points.js").write_text("\n".join(lines), encoding="utf-8")
    print("kept per class:", counts, "| dropped for spacing:", dropped)
    short = [n for n, c in counts.items() if c < 30]
    if short:
        raise SystemExit(f"Fewer than 30 points for: {short}. Label more candidates before running the classifier.")


if __name__ == "__main__":
    main()
